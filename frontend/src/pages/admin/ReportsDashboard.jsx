import PageHeader from '../../components/PageHeader.jsx';

const reportSections = [
  { key: 'routeBookings', title: 'Bookings by Route' },
  { key: 'revenue', title: 'Payment Revenue' },
  { key: 'passengerTrips', title: 'Passenger Trips' },
  { key: 'maintenanceDue', title: 'Maintenance Due' },
  { key: 'feedbackSummary', title: 'Feedback Summary' },
];

export default function ReportsDashboard({ report }) {
  return (
    <section className="page">
      <PageHeader title="Reports Dashboard" subtitle="Reports generated by the Oracle procedures" />
      <div className="report-grid">
        {reportSections.map(({ key, title }) => {
          const lines = Array.isArray(report?.[key]) ? report[key] : [];
          return (
            <section className="report-panel" aria-labelledby={`${key}-title`} key={key}>
              <h2 id={`${key}-title`}>{title}</h2>
              {lines.length ? (
                <ul style={{ paddingLeft: '20px', margin: 0, color: '#475569', lineHeight: 1.8 }}>
                  {lines.map((line, index) => <li key={`${key}-${index}`}>{line}</li>)}
                </ul>
              ) : (
                <p className="report-empty">No report rows are available.</p>
              )}
            </section>
          );
        })}
      </div>
    </section>
  );
}
