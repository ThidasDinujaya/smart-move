-- ============================================================
-- 1. VEHICLES TABLE
-- ============================================================

CREATE TABLE vehicles (
    vehicle_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1000 INCREMENT BY 1),

    registration_no VARCHAR2(20) NOT NULL,
    vehicle_type VARCHAR2(30) NOT NULL,
    brand VARCHAR2(60) NOT NULL,
    model VARCHAR2(60),
    manufacture_year NUMBER(4),
    capacity NUMBER(4) NOT NULL,

    vehicle_status VARCHAR2(20)
        DEFAULT 'Active' NOT NULL,

    last_service_date DATE,
    next_service_date DATE,

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_vehicles
        PRIMARY KEY (vehicle_id),

    CONSTRAINT uq_vehicles_registration
        UNIQUE (registration_no),

    CONSTRAINT ck_vehicles_capacity
        CHECK (capacity > 0),

    CONSTRAINT ck_vehicles_year
        CHECK (
            manufacture_year IS NULL
            OR manufacture_year >= 1990
        ),

    CONSTRAINT ck_vehicles_status
        CHECK (
            vehicle_status IN (
                'Active',
                'Maintenance',
                'Inactive'
            )
        )
);

-- ============================================================
-- 2. DRIVERS TABLE
-- ============================================================

CREATE TABLE drivers (
    driver_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1000 INCREMENT BY 1),

    full_name VARCHAR2(120) NOT NULL,
    nic VARCHAR2(20) NOT NULL,
    phone VARCHAR2(25) NOT NULL,
    email VARCHAR2(254),
    address VARCHAR2(500),
    license_no VARCHAR2(40) NOT NULL,

    assigned_vehicle_id NUMBER,

    driver_status VARCHAR2(20)
        DEFAULT 'Active' NOT NULL,

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_drivers
        PRIMARY KEY (driver_id),

    CONSTRAINT uq_drivers_nic
        UNIQUE (nic),

    CONSTRAINT uq_drivers_license
        UNIQUE (license_no),

    CONSTRAINT fk_drivers_vehicle
        FOREIGN KEY (assigned_vehicle_id)
        REFERENCES vehicles (vehicle_id),

    CONSTRAINT ck_drivers_status
        CHECK (
            driver_status IN (
                'Active',
                'On Leave',
                'Inactive'
            )
        )
);

-- ============================================================
-- 3. ROUTES TABLE
-- ============================================================

CREATE TABLE routes (
    route_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1000 INCREMENT BY 1),

    route_no VARCHAR2(20) NOT NULL,
    route_name VARCHAR2(120) NOT NULL,

    start_location VARCHAR2(120) NOT NULL,
    end_location VARCHAR2(120) NOT NULL,

    distance_km NUMBER(8,2) NOT NULL,
    estimated_duration_minutes NUMBER(6),

    fare NUMBER(10,2) DEFAULT 0 NOT NULL,

    route_status VARCHAR2(20)
        DEFAULT 'Active' NOT NULL,

    description VARCHAR2(1000),

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_routes
        PRIMARY KEY (route_id),

    CONSTRAINT uq_routes_route_no
        UNIQUE (route_no),

    CONSTRAINT ck_routes_distance
        CHECK (distance_km > 0),

    CONSTRAINT ck_routes_duration
        CHECK (
            estimated_duration_minutes IS NULL
            OR estimated_duration_minutes > 0
        ),

    CONSTRAINT ck_routes_fare
        CHECK (fare >= 0),

    CONSTRAINT ck_routes_status
        CHECK (
            route_status IN (
                'Active',
                'Inactive'
            )
        ),

    CONSTRAINT ck_routes_locations
        CHECK (
            UPPER(start_location)
            <> UPPER(end_location)
        )
);

