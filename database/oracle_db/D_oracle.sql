-- ============================================================
-- 7. FLEET SUMMARY REPORT
-- ============================================================

CREATE OR REPLACE PROCEDURE sp_report_fleet_summary
IS
    v_found BOOLEAN := FALSE;
BEGIN

    DBMS_OUTPUT.PUT_LINE(
        '--- Fleet Summary Report ---'
    );

    FOR r IN (
        SELECT
            vehicle_type,
            vehicle_status,
            COUNT(*) AS vehicle_count
        FROM vehicles
        GROUP BY
            vehicle_type,
            vehicle_status
        ORDER BY
            vehicle_type,
            vehicle_status
    )
    LOOP
        v_found := TRUE;

        DBMS_OUTPUT.PUT_LINE(
            r.vehicle_type
            || ' | '
            || r.vehicle_status
            || ' | vehicles: '
            || r.vehicle_count
        );

    END LOOP;

    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE(
            'No vehicles found.'
        );
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Fleet summary report failed: '
            || SQLERRM
        );
        RAISE;
END;
/

-- ============================================================
-- 8. DRIVER ASSIGNMENT REPORT
-- ============================================================

CREATE OR REPLACE PROCEDURE sp_report_driver_assignments
IS
    v_found BOOLEAN := FALSE;
BEGIN

    DBMS_OUTPUT.PUT_LINE(
        '--- Driver Assignment Report ---'
    );

    FOR r IN (
        SELECT
            d.full_name,
            d.driver_status,
            v.registration_no,
            v.vehicle_type
        FROM drivers d
        LEFT JOIN vehicles v
            ON d.assigned_vehicle_id = v.vehicle_id
        ORDER BY d.full_name
    )
    LOOP
        v_found := TRUE;

        DBMS_OUTPUT.PUT_LINE(
            r.full_name
            || ' | '
            || r.driver_status
            || ' | vehicle: '
            || NVL(
                r.registration_no,
                'Not Assigned'
            )
            || ' | type: '
            || NVL(
                r.vehicle_type,
                'N/A'
            )
        );

    END LOOP;

    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE(
            'No drivers found.'
        );
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(
            'Driver assignment report failed: '
            || SQLERRM
        );
        RAISE;
END;
/

-- ============================================================
