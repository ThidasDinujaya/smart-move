-- J owns payment processing, maintenance management, feedback, and the related reports.
-- Run after D_oracle.sql and leader_oracle.sql because its records reference their tables.

CREATE TABLE payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    payment_ref VARCHAR2(30) NOT NULL,
    booking_id NUMBER NOT NULL,
    amount NUMBER(12,2) NOT NULL,
    payment_method VARCHAR2(30) NOT NULL,
    payment_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    payment_status VARCHAR2(20) DEFAULT 'Pending' NOT NULL,
    provider_reference VARCHAR2(100),
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT uq_payments_ref UNIQUE (payment_ref),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (payment_status IN ('Pending', 'Successful', 'Failed', 'Refunded'))
);

-- Maintenance rows keep the service history for each vehicle.
CREATE TABLE maintenance (
    maintenance_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    vehicle_id NUMBER NOT NULL,
    maintenance_type VARCHAR2(80) NOT NULL,
    service_date DATE NOT NULL,
    next_service_date DATE,
    service_cost NUMBER(12,2) DEFAULT 0 NOT NULL,
    provider VARCHAR2(120),
    maintenance_status VARCHAR2(20) DEFAULT 'Scheduled' NOT NULL,
    description VARCHAR2(1000),
    CONSTRAINT pk_maintenance PRIMARY KEY (maintenance_id),
    CONSTRAINT fk_maintenance_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (vehicle_id),
    CONSTRAINT ck_maintenance_cost CHECK (service_cost >= 0),
    CONSTRAINT ck_maintenance_next CHECK (next_service_date IS NULL OR next_service_date >= service_date),
    CONSTRAINT ck_maintenance_status CHECK (maintenance_status IN ('Scheduled', 'Pending', 'Completed', 'Overdue'))
);

CREATE OR REPLACE TRIGGER trg_maintenance_update_vehicle
AFTER INSERT OR UPDATE OF maintenance_status, service_date, next_service_date ON maintenance
FOR EACH ROW
WHEN (NEW.maintenance_status = 'Completed')
BEGIN
    UPDATE vehicles
       SET last_service_date = :NEW.service_date,
           next_service_date = :NEW.next_service_date
     WHERE vehicle_id = :NEW.vehicle_id;
END;
/

-- Feedback stores separate ratings so the reports can compare drivers and vehicles.
CREATE TABLE feedback (
    feedback_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    passenger_id NUMBER NOT NULL,
    trip_id NUMBER NOT NULL,
    overall_rating NUMBER(1) NOT NULL,
    driver_rating NUMBER(1),
    vehicle_rating NUMBER(1),
    comment_text VARCHAR2(2000),
    review_status VARCHAR2(20) DEFAULT 'New' NOT NULL,
    submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_feedback PRIMARY KEY (feedback_id),
    CONSTRAINT uq_feedback_passenger_trip UNIQUE (passenger_id, trip_id),
    CONSTRAINT fk_feedback_passenger FOREIGN KEY (passenger_id) REFERENCES passengers (passenger_id),
    CONSTRAINT fk_feedback_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id),
    CONSTRAINT ck_feedback_overall CHECK (overall_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_driver CHECK (driver_rating IS NULL OR driver_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_vehicle CHECK (vehicle_rating IS NULL OR vehicle_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_status CHECK (review_status IN ('New', 'Reviewed', 'Hidden'))
);

CREATE OR REPLACE TRIGGER trg_feedback_completed_trip
BEFORE INSERT OR UPDATE OF passenger_id, trip_id ON feedback
FOR EACH ROW
DECLARE
    v_trip_status trips.trip_status%TYPE;
    v_booking_count NUMBER;
BEGIN
    SELECT trip_status
      INTO v_trip_status
      FROM trips
     WHERE trip_id = :NEW.trip_id;

    IF v_trip_status <> 'Completed' THEN
        RAISE_APPLICATION_ERROR(-20020, 'Feedback can only be submitted for completed trips.');
    END IF;

    SELECT COUNT(*)
      INTO v_booking_count
      FROM bookings
     WHERE passenger_id = :NEW.passenger_id
       AND trip_id = :NEW.trip_id
       AND booking_status = 'Completed';

    IF v_booking_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'The passenger must have completed a booking for this trip.');
    END IF;
END;
/

