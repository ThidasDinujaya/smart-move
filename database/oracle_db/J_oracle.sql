-- Record a payment attempt and confirm the booking after a successful payment.
CREATE OR REPLACE PROCEDURE sp_record_payment (
    p_booking_id IN NUMBER,
    p_amount IN NUMBER,
    p_payment_method IN VARCHAR2,
    p_payment_status IN VARCHAR2 DEFAULT 'Successful',
    p_provider_reference IN VARCHAR2 DEFAULT NULL
)
IS
    v_booking_amount bookings.total_amount%TYPE;
    v_booking_status bookings.booking_status%TYPE;
    v_status VARCHAR2(20) := INITCAP(TRIM(p_payment_status));
BEGIN
    SAVEPOINT record_payment_start;

    SELECT total_amount, booking_status
      INTO v_booking_amount, v_booking_status
      FROM bookings
     WHERE booking_id = p_booking_id
       FOR UPDATE;

    IF v_booking_status IN ('Cancelled', 'Completed') THEN
        RAISE_APPLICATION_ERROR(-20040, 'This booking cannot accept another payment.');
    END IF;

    IF v_status IS NULL OR v_status NOT IN ('Successful', 'Failed', 'Pending') THEN
        RAISE_APPLICATION_ERROR(-20041, 'Payment status must be Successful, Failed, or Pending.');
    END IF;

    IF p_amount IS NULL OR p_amount < 0 THEN
        RAISE_APPLICATION_ERROR(-20042, 'Payment amount cannot be negative.');
    END IF;

    IF p_payment_method IS NULL OR TRIM(p_payment_method) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20047, 'Payment method is required.');
    END IF;

    IF v_status = 'Successful' AND p_amount <> v_booking_amount THEN
        RAISE_APPLICATION_ERROR(-20043, 'Successful payment must match the booking total.');
    END IF;

    INSERT INTO payments (payment_ref, booking_id, amount, payment_method, payment_status, provider_reference)
    VALUES ('SMP-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 20), p_booking_id, p_amount, INITCAP(TRIM(p_payment_method)), v_status, p_provider_reference);

    IF v_status = 'Successful' THEN
        UPDATE bookings
           SET booking_status = 'Confirmed'
         WHERE booking_id = p_booking_id;
        UPDATE tickets
           SET ticket_status = 'Issued'
         WHERE booking_id = p_booking_id
           AND ticket_status = 'Reserved';
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO record_payment_start;
        RAISE_APPLICATION_ERROR(-20044, 'Booking was not found.');
    WHEN OTHERS THEN
        ROLLBACK TO record_payment_start;
        RAISE;
END;
/

-- Call this only after the payment provider confirms a refund.
CREATE OR REPLACE PROCEDURE sp_mark_payment_refunded (p_payment_id IN NUMBER)
IS
    v_payment_status payments.payment_status%TYPE;
BEGIN
    SAVEPOINT refund_payment_start;

    SELECT payment_status
      INTO v_payment_status
      FROM payments
     WHERE payment_id = p_payment_id
       FOR UPDATE;

    IF v_payment_status <> 'Successful' THEN
        RAISE_APPLICATION_ERROR(-20048, 'Only successful payments can be marked as refunded.');
    END IF;

    UPDATE payments
       SET payment_status = 'Refunded'
     WHERE payment_id = p_payment_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO refund_payment_start;
        RAISE_APPLICATION_ERROR(-20049, 'Payment was not found.');
    WHEN OTHERS THEN
        ROLLBACK TO refund_payment_start;
        RAISE;
END;
/

-- Report successful ticket revenue for an inclusive date range.
CREATE OR REPLACE PROCEDURE sp_report_revenue (p_from IN DATE, p_to IN DATE)
IS
    v_revenue NUMBER(14,2);
BEGIN
    IF p_from > p_to THEN
        RAISE_APPLICATION_ERROR(-20050, 'The start date must be before the end date.');
    END IF;

    SELECT NVL(SUM(amount), 0)
      INTO v_revenue
      FROM payments
     WHERE payment_status = 'Successful'
       AND payment_date >= p_from
       AND payment_date < p_to + 1;

    DBMS_OUTPUT.PUT_LINE('Successful revenue: LKR ' || TO_CHAR(v_revenue, 'FM999999999990.00'));
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Revenue report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report vehicles whose next service date has passed or is approaching.
CREATE OR REPLACE PROCEDURE sp_report_maintenance_due (p_as_of IN DATE DEFAULT TRUNC(SYSDATE))
IS
    v_found BOOLEAN := FALSE;
BEGIN
    FOR r IN (
        SELECT vehicle_id, registration_no, vehicle_type, next_service_date, vehicle_status
          FROM vehicles
         WHERE next_service_date IS NOT NULL
           AND next_service_date <= p_as_of + 30
         ORDER BY next_service_date
    ) LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.registration_no || ' | ' || r.vehicle_type || ' | service due: ' || TO_CHAR(r.next_service_date, 'YYYY-MM-DD') || ' | ' || r.vehicle_status);
    END LOOP;
    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No vehicles are due for service in the next 30 days.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Maintenance report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report overall, driver, and vehicle feedback averages and rating distribution.
CREATE OR REPLACE PROCEDURE sp_report_feedback_summary
IS
    v_total NUMBER;
    v_overall NUMBER(5,2);
    v_driver NUMBER(5,2);
    v_vehicle NUMBER(5,2);
BEGIN
    SELECT COUNT(*), ROUND(AVG(overall_rating), 2), ROUND(AVG(driver_rating), 2), ROUND(AVG(vehicle_rating), 2)
      INTO v_total, v_overall, v_driver, v_vehicle
      FROM feedback
     WHERE review_status <> 'Hidden';

    DBMS_OUTPUT.PUT_LINE('Visible reviews: ' || v_total);
    DBMS_OUTPUT.PUT_LINE('Average overall rating: ' || NVL(TO_CHAR(v_overall), 'N/A'));
    DBMS_OUTPUT.PUT_LINE('Average driver rating: ' || NVL(TO_CHAR(v_driver), 'N/A'));
    DBMS_OUTPUT.PUT_LINE('Average vehicle rating: ' || NVL(TO_CHAR(v_vehicle), 'N/A'));

    FOR r IN (
        SELECT overall_rating, COUNT(*) AS rating_count
          FROM feedback
         WHERE review_status <> 'Hidden'
         GROUP BY overall_rating
         ORDER BY overall_rating DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(r.overall_rating || ' stars: ' || r.rating_count);
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Feedback report failed: ' || SQLERRM);
        RAISE;
END;
/

