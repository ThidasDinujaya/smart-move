-- Create the SmartMove relational tables in SYSTEM on XEPDB1.

CREATE TABLE passengers (
    passenger_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    full_name VARCHAR2(120) NOT NULL,
    email VARCHAR2(254) NOT NULL,
    phone VARCHAR2(25) NOT NULL,
    nic VARCHAR2(20),
    gender VARCHAR2(20),
    status VARCHAR2(20) DEFAULT 'Active' NOT NULL,
    registered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_passengers PRIMARY KEY (passenger_id),
    CONSTRAINT uq_passengers_email UNIQUE (email),
    CONSTRAINT uq_passengers_nic UNIQUE (nic),
    CONSTRAINT ck_passengers_status CHECK (status IN ('Active', 'Inactive'))
);

CREATE TABLE users (
    user_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    passenger_id NUMBER(19) NOT NULL,
    email VARCHAR2(254) NOT NULL,
    password VARCHAR2(128) NOT NULL,
    role_code VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    account_status VARCHAR2(20) DEFAULT 'Active' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_passenger UNIQUE (passenger_id),
    CONSTRAINT fk_users_passenger FOREIGN KEY (passenger_id) REFERENCES passengers (passenger_id),
    CONSTRAINT ck_users_role CHECK (role_code IN ('ADMIN', 'CUSTOMER', 'OPERATIONS', 'FINANCE', 'SUPPORT')),
    CONSTRAINT ck_users_status CHECK (account_status IN ('Active', 'Inactive'))
);

CREATE TABLE drivers (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    name VARCHAR2(255) NOT NULL,
    nic VARCHAR2(255) NOT NULL,
    license_no VARCHAR2(255) NOT NULL,
    contact VARCHAR2(255),
    email VARCHAR2(255),
    vehicle_id NUMBER(19),
    image_data CLOB,
    address VARCHAR2(255),
    status VARCHAR2(255),
    CONSTRAINT pk_drivers PRIMARY KEY (id),
    CONSTRAINT uq_drivers_nic UNIQUE (nic),
    CONSTRAINT uq_drivers_license UNIQUE (license_no)
);

CREATE TABLE routes (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    route_no VARCHAR2(255) NOT NULL,
    route_name VARCHAR2(255) NOT NULL,
    start_location VARCHAR2(255) NOT NULL,
    end_location VARCHAR2(255) NOT NULL,
    distance FLOAT(53),
    fare FLOAT(53),
    estimated_time VARCHAR2(255),
    description VARCHAR2(1000),
    status VARCHAR2(255),
    CONSTRAINT pk_routes PRIMARY KEY (id),
    CONSTRAINT uq_routes_route_no UNIQUE (route_no)
);

CREATE TABLE vehicles (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    vehicle_no VARCHAR2(255) NOT NULL,
    vehicle_type VARCHAR2(255),
    brand VARCHAR2(255),
    model VARCHAR2(255),
    manufacture_year NUMBER(10),
    seating_capacity NUMBER(10),
    fuel_type VARCHAR2(255),
    last_service_date DATE,
    status VARCHAR2(255),
    CONSTRAINT pk_vehicles PRIMARY KEY (id),
    CONSTRAINT uq_vehicles_vehicle_no UNIQUE (vehicle_no),
    CONSTRAINT ck_vehicles_capacity CHECK (seating_capacity IS NULL OR seating_capacity > 0)
);

ALTER TABLE drivers ADD CONSTRAINT fk_drivers_vehicle
    FOREIGN KEY (vehicle_id) REFERENCES vehicles (id);

CREATE TABLE trips (
    trip_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    route_id NUMBER(19) NOT NULL,
    vehicle_id NUMBER(19) NOT NULL,
    driver_id NUMBER(19) NOT NULL,
    trip_date DATE NOT NULL,
    departure_time TIMESTAMP NOT NULL,
    arrival_time TIMESTAMP NOT NULL,
    seat_capacity NUMBER(10) NOT NULL,
    fare NUMBER(12,2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'Scheduled' NOT NULL,
    notes VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_trips PRIMARY KEY (trip_id),
    CONSTRAINT ck_trips_capacity CHECK (seat_capacity > 0),
    CONSTRAINT ck_trips_fare CHECK (fare >= 0),
    CONSTRAINT ck_trips_status CHECK (status IN ('Scheduled', 'Cancelled', 'Completed')),
    CONSTRAINT fk_trips_route FOREIGN KEY (route_id) REFERENCES routes (id),
    CONSTRAINT fk_trips_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id),
    CONSTRAINT fk_trips_driver FOREIGN KEY (driver_id) REFERENCES drivers (id)
);

CREATE TABLE bookings (
    booking_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    booking_reference VARCHAR2(30) NOT NULL,
    passenger_id NUMBER(19) NOT NULL,
    trip_id NUMBER(19) NOT NULL,
    booking_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    seat_count NUMBER(10) NOT NULL,
    total_amount NUMBER(12,2) NOT NULL,
    booking_status VARCHAR2(25) DEFAULT 'Pending Payment' NOT NULL,
    CONSTRAINT pk_bookings PRIMARY KEY (booking_id),
    CONSTRAINT uq_bookings_reference UNIQUE (booking_reference),
    CONSTRAINT ck_bookings_seats CHECK (seat_count > 0),
    CONSTRAINT ck_bookings_total CHECK (total_amount >= 0),
    CONSTRAINT ck_bookings_status CHECK (booking_status IN ('Pending Payment', 'Confirmed', 'Cancelled', 'Completed')),
    CONSTRAINT fk_bookings_passenger FOREIGN KEY (passenger_id) REFERENCES passengers (passenger_id),
    CONSTRAINT fk_bookings_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id)
);

CREATE TABLE tickets (
    ticket_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    ticket_number VARCHAR2(30) NOT NULL,
    booking_id NUMBER(19) NOT NULL,
    trip_id NUMBER(19) NOT NULL,
    seat_number VARCHAR2(10) NOT NULL,
    ticket_status VARCHAR2(20) DEFAULT 'Reserved' NOT NULL,
    issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_tickets PRIMARY KEY (ticket_id),
    CONSTRAINT uq_tickets_number UNIQUE (ticket_number),
    CONSTRAINT uq_tickets_booking_seat UNIQUE (booking_id, seat_number),
    CONSTRAINT ck_tickets_status CHECK (ticket_status IN ('Reserved', 'Confirmed', 'Issued', 'Cancelled')),
    CONSTRAINT fk_tickets_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id),
    CONSTRAINT fk_tickets_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id)
);

CREATE TABLE payments (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    booking_id NUMBER(19) NOT NULL,
    amount NUMBER(12,2) NOT NULL,
    payment_method VARCHAR2(255),
    payment_status VARCHAR2(20) DEFAULT 'Successful' NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    refunded_at TIMESTAMP,
    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uq_payments_booking UNIQUE (booking_id),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (payment_status IN ('Successful', 'Refunded')),
    CONSTRAINT ck_payments_refund_date CHECK
        ((payment_status = 'Refunded' AND refunded_at IS NOT NULL)
         OR (payment_status = 'Successful' AND refunded_at IS NULL)),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id)
        REFERENCES bookings (booking_id)
);

CREATE TABLE maintenance (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    vehicle_id NUMBER(19) NOT NULL,
    service_type VARCHAR2(255),
    description VARCHAR2(255),
    cost NUMBER(19,2),
    start_date DATE,
    next_service_date DATE,
    provider VARCHAR2(255),
    status VARCHAR2(255),
    CONSTRAINT pk_maintenance PRIMARY KEY (id),
    CONSTRAINT ck_maintenance_cost CHECK (cost IS NULL OR cost >= 0),
    CONSTRAINT ck_maintenance_status CHECK (status IS NULL OR status IN ('Scheduled', 'Pending', 'Due', 'Completed', 'Overdue')),
    CONSTRAINT fk_maintenance_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
);

CREATE TABLE feedback (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    passenger_id NUMBER(19) NOT NULL,
    trip_id NUMBER(19) NOT NULL,
    rating NUMBER(1) NOT NULL,
    driver_rating NUMBER(1),
    vehicle_rating NUMBER(1),
    review_status VARCHAR2(20) DEFAULT 'NEW' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_feedback PRIMARY KEY (id),
    CONSTRAINT uq_feedback_passenger_trip UNIQUE (passenger_id, trip_id),
    CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_driver_rating CHECK (driver_rating IS NULL OR driver_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_vehicle_rating CHECK (vehicle_rating IS NULL OR vehicle_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_review_status CHECK (review_status IN ('NEW', 'REVIEWED', 'HIDDEN')),
    CONSTRAINT fk_feedback_passenger FOREIGN KEY (passenger_id) REFERENCES passengers (passenger_id),
    CONSTRAINT fk_feedback_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id)
);
