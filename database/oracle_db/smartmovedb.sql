-- Return the number of unoccupied seats for a trip.
CREATE OR REPLACE FUNCTION fn_available_seats (p_trip_id IN NUMBER)
RETURN NUMBER
IS
    v_capacity NUMBER;
    v_reserved NUMBER;
BEGIN
    SELECT seat_capacity
      INTO v_capacity
      FROM trips
     WHERE trip_id = p_trip_id;

    SELECT COUNT(*)
      INTO v_reserved
      FROM tickets
     WHERE trip_id = p_trip_id
       AND ticket_status IN ('Reserved', 'Issued', 'Used');

    RETURN GREATEST(v_capacity - v_reserved, 0);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20030, 'Trip was not found.');
END;
/

-- Search results expose active trips and calculate seats from current tickets.
CREATE OR REPLACE VIEW vw_search_trips AS
SELECT t.trip_id,
       r.route_id,
       r.route_no,
       r.route_name,
       r.start_location,
       r.end_location,
       t.departure_at,
       t.arrival_at,
       v.vehicle_id,
       v.registration_no,
       v.vehicle_type,
       v.brand,
       v.model,
       d.driver_id,
       d.full_name AS driver_name,
       t.fare,
       t.seat_capacity,
       fn_available_seats(t.trip_id) AS available_seats
  FROM trips t
  JOIN routes r ON r.route_id = t.route_id
  JOIN vehicles v ON v.vehicle_id = t.vehicle_id
  JOIN drivers d ON d.driver_id = t.driver_id
 WHERE t.trip_status = 'Scheduled'
   AND r.route_status = 'Active'
   AND v.vehicle_status = 'Active'
   AND d.driver_status = 'Active';

-- Create a booking and reserve each selected seat in one transaction.
CREATE OR REPLACE PROCEDURE sp_create_booking (
    p_passenger_id IN NUMBER,
    p_trip_id IN NUMBER,
    p_seats IN SYS.ODCIVARCHAR2LIST,
    p_booking_id OUT NUMBER
)
IS
    v_fare NUMBER(10,2);
    v_capacity NUMBER;
    v_trip_status trips.trip_status%TYPE;
    v_departure trips.departure_at%TYPE;
    v_active_tickets NUMBER;
    v_active_passengers NUMBER;
    v_seat_no VARCHAR2(10);
BEGIN
    SAVEPOINT create_booking_start;

    IF p_seats IS NULL OR p_seats.COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20031, 'Choose at least one seat.');
    END IF;

    SELECT fare, seat_capacity, trip_status, departure_at
      INTO v_fare, v_capacity, v_trip_status, v_departure
      FROM trips
     WHERE trip_id = p_trip_id
       FOR UPDATE;

    IF v_trip_status <> 'Scheduled' OR v_departure <= SYSTIMESTAMP THEN
        RAISE_APPLICATION_ERROR(-20032, 'Only upcoming scheduled trips can be booked.');
    END IF;

    SELECT COUNT(*)
      INTO v_active_passengers
      FROM passengers
     WHERE passenger_id = p_passenger_id
       AND passenger_status = 'Active';

    IF v_active_passengers = 0 THEN
        RAISE_APPLICATION_ERROR(-20033, 'An active passenger account is required.');
    END IF;

    IF p_seats.COUNT > v_capacity THEN
        RAISE_APPLICATION_ERROR(-20034, 'The selected seats exceed trip capacity.');
    END IF;

    FOR i IN 1 .. p_seats.COUNT LOOP
        v_seat_no := UPPER(TRIM(p_seats(i)));
        IF v_seat_no IS NULL THEN
            RAISE_APPLICATION_ERROR(-20035, 'Seat numbers cannot be empty.');
        END IF;
        FOR j IN 1 .. i - 1 LOOP
            IF v_seat_no = UPPER(TRIM(p_seats(j))) THEN
                RAISE_APPLICATION_ERROR(-20036, 'The same seat was selected more than once.');
            END IF;
        END LOOP;
    END LOOP;

    SELECT COUNT(*)
      INTO v_active_tickets
      FROM tickets
     WHERE trip_id = p_trip_id
       AND ticket_status IN ('Reserved', 'Issued', 'Used');

    IF v_active_tickets + p_seats.COUNT > v_capacity THEN
        RAISE_APPLICATION_ERROR(-20037, 'There are not enough seats remaining.');
    END IF;

    INSERT INTO bookings (booking_ref, passenger_id, trip_id, seat_count, total_amount, booking_status)
    VALUES ('SMB-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 20), p_passenger_id, p_trip_id, p_seats.COUNT, v_fare * p_seats.COUNT, 'Pending Payment')
    RETURNING booking_id INTO p_booking_id;

    FOR i IN 1 .. p_seats.COUNT LOOP
        INSERT INTO tickets (ticket_no, booking_id, trip_id, seat_no, ticket_status)
        VALUES ('SMT-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 20), p_booking_id, p_trip_id, UPPER(TRIM(p_seats(i))), 'Reserved');
    END LOOP;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO create_booking_start;
        RAISE_APPLICATION_ERROR(-20038, 'Trip or passenger record was not found.');
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO create_booking_start;
        RAISE_APPLICATION_ERROR(-20039, 'A selected seat is already reserved for this trip.');
    WHEN OTHERS THEN
        ROLLBACK TO create_booking_start;
        RAISE;
END;
/

-- Record a payment attempt and confirm the booking after a successful payment.
CREATE OR REPLACE PROCEDURE sp_record_payment (
    p_booking_id IN NUMBER,
    p_amount IN NUMBER,
    p_payment_method IN VARCHAR2,
    p_payment_status IN VARCHAR2 DEFAULT 'Successful',
    p_provider_reference IN VARCHAR2 DEFAULT NULL
)
IS
    v_booking_amount bookings.total_amount%TYPE;
    v_booking_status bookings.booking_status%TYPE;
    v_status VARCHAR2(20) := INITCAP(TRIM(p_payment_status));
BEGIN
    SAVEPOINT record_payment_start;

    SELECT total_amount, booking_status
      INTO v_booking_amount, v_booking_status
      FROM bookings
     WHERE booking_id = p_booking_id
       FOR UPDATE;

    IF v_booking_status IN ('Cancelled', 'Completed') THEN
        RAISE_APPLICATION_ERROR(-20040, 'This booking cannot accept another payment.');
    END IF;

    IF v_status IS NULL OR v_status NOT IN ('Successful', 'Failed', 'Pending') THEN
        RAISE_APPLICATION_ERROR(-20041, 'Payment status must be Successful, Failed, or Pending.');
    END IF;

    IF p_amount IS NULL OR p_amount < 0 THEN
        RAISE_APPLICATION_ERROR(-20042, 'Payment amount cannot be negative.');
    END IF;

    IF p_payment_method IS NULL OR TRIM(p_payment_method) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20047, 'Payment method is required.');
    END IF;

    IF v_status = 'Successful' AND p_amount <> v_booking_amount THEN
        RAISE_APPLICATION_ERROR(-20043, 'Successful payment must match the booking total.');
    END IF;

    INSERT INTO payments (payment_ref, booking_id, amount, payment_method, payment_status, provider_reference)
    VALUES ('SMP-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 20), p_booking_id, p_amount, INITCAP(TRIM(p_payment_method)), v_status, p_provider_reference);

    IF v_status = 'Successful' THEN
        UPDATE bookings
           SET booking_status = 'Confirmed'
         WHERE booking_id = p_booking_id;
        UPDATE tickets
           SET ticket_status = 'Issued'
         WHERE booking_id = p_booking_id
           AND ticket_status = 'Reserved';
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO record_payment_start;
        RAISE_APPLICATION_ERROR(-20044, 'Booking was not found.');
    WHEN OTHERS THEN
        ROLLBACK TO record_payment_start;
        RAISE;
END;
/

-- Call this only after the payment provider confirms a refund.
CREATE OR REPLACE PROCEDURE sp_mark_payment_refunded (p_payment_id IN NUMBER)
IS
    v_payment_status payments.payment_status%TYPE;
BEGIN
    SAVEPOINT refund_payment_start;

    SELECT payment_status
      INTO v_payment_status
      FROM payments
     WHERE payment_id = p_payment_id
       FOR UPDATE;

    IF v_payment_status <> 'Successful' THEN
        RAISE_APPLICATION_ERROR(-20048, 'Only successful payments can be marked as refunded.');
    END IF;

    UPDATE payments
       SET payment_status = 'Refunded'
     WHERE payment_id = p_payment_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO refund_payment_start;
        RAISE_APPLICATION_ERROR(-20049, 'Payment was not found.');
    WHEN OTHERS THEN
        ROLLBACK TO refund_payment_start;
        RAISE;
END;
/

-- Cancel a pending or confirmed booking and release its reserved seats.
-- Mark a successful payment as refunded only after the payment provider confirms the refund.
CREATE OR REPLACE PROCEDURE sp_cancel_booking (p_booking_id IN NUMBER)
IS
    v_booking_status bookings.booking_status%TYPE;
BEGIN
    SAVEPOINT cancel_booking_start;

    SELECT booking_status
      INTO v_booking_status
      FROM bookings
     WHERE booking_id = p_booking_id
       FOR UPDATE;

    IF v_booking_status NOT IN ('Pending Payment', 'Confirmed') THEN
        RAISE_APPLICATION_ERROR(-20045, 'Only pending or confirmed bookings can be cancelled.');
    END IF;

    UPDATE bookings
       SET booking_status = 'Cancelled'
     WHERE booking_id = p_booking_id;

    UPDATE tickets
       SET ticket_status = 'Cancelled'
     WHERE booking_id = p_booking_id
       AND ticket_status IN ('Reserved', 'Issued');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO cancel_booking_start;
        RAISE_APPLICATION_ERROR(-20046, 'Booking was not found.');
    WHEN OTHERS THEN
        ROLLBACK TO cancel_booking_start;
        RAISE;
END;
/

-- Report the routes with the most confirmed or completed bookings.
CREATE OR REPLACE PROCEDURE sp_report_popular_routes (p_from IN DATE, p_to IN DATE)
IS
    v_found BOOLEAN := FALSE;
BEGIN
    DBMS_OUTPUT.PUT_LINE('Popular routes from ' || TO_CHAR(p_from, 'YYYY-MM-DD') || ' to ' || TO_CHAR(p_to, 'YYYY-MM-DD'));
    FOR r IN (
        SELECT ro.route_no, ro.route_name, COUNT(DISTINCT b.booking_id) AS booking_count
          FROM routes ro
          JOIN trips t ON t.route_id = ro.route_id
          JOIN bookings b ON b.trip_id = t.trip_id
         WHERE b.booking_status IN ('Confirmed', 'Completed')
           AND t.departure_at >= p_from
           AND t.departure_at < p_to + 1
         GROUP BY ro.route_no, ro.route_name
         ORDER BY booking_count DESC, ro.route_name
    ) LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.route_no || ' | ' || r.route_name || ' | bookings: ' || r.booking_count);
    END LOOP;
    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No matching bookings were found.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Popular route report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report successful ticket revenue for an inclusive date range.
CREATE OR REPLACE PROCEDURE sp_report_revenue (p_from IN DATE, p_to IN DATE)
IS
    v_revenue NUMBER(14,2);
BEGIN
    IF p_from > p_to THEN
        RAISE_APPLICATION_ERROR(-20050, 'The start date must be before the end date.');
    END IF;

    SELECT NVL(SUM(amount), 0)
      INTO v_revenue
      FROM payments
     WHERE payment_status = 'Successful'
       AND payment_date >= p_from
       AND payment_date < p_to + 1;

    DBMS_OUTPUT.PUT_LINE('Successful revenue: LKR ' || TO_CHAR(v_revenue, 'FM999999999990.00'));
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Revenue report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report one passenger's travel history with an explicit cursor.
CREATE OR REPLACE PROCEDURE sp_report_passenger_history (p_passenger_id IN NUMBER)
IS
    CURSOR c_history IS
        SELECT b.booking_ref, r.route_name, t.departure_at, t.arrival_at, v.registration_no,
               LISTAGG(tk.seat_no, ', ') WITHIN GROUP (ORDER BY tk.seat_no) AS seat_numbers,
               b.total_amount, b.booking_status
          FROM bookings b
          JOIN trips t ON t.trip_id = b.trip_id
          JOIN routes r ON r.route_id = t.route_id
          JOIN vehicles v ON v.vehicle_id = t.vehicle_id
          LEFT JOIN tickets tk ON tk.booking_id = b.booking_id
         WHERE b.passenger_id = p_passenger_id
         GROUP BY b.booking_ref, r.route_name, t.departure_at, t.arrival_at, v.registration_no, b.total_amount, b.booking_status
         ORDER BY t.departure_at DESC;
    v_found BOOLEAN := FALSE;
BEGIN
    FOR r IN c_history LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.booking_ref || ' | ' || r.route_name || ' | ' || TO_CHAR(r.departure_at, 'YYYY-MM-DD HH24:MI') || ' | ' || NVL(r.seat_numbers, '-') || ' | LKR ' || TO_CHAR(r.total_amount, 'FM999999990.00') || ' | ' || r.booking_status);
    END LOOP;
    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No travel history was found for passenger ' || p_passenger_id || '.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Passenger history report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report vehicles whose next service date has passed or is approaching.
CREATE OR REPLACE PROCEDURE sp_report_maintenance_due (p_as_of IN DATE DEFAULT TRUNC(SYSDATE))
IS
    v_found BOOLEAN := FALSE;
BEGIN
    FOR r IN (
        SELECT vehicle_id, registration_no, vehicle_type, next_service_date, vehicle_status
          FROM vehicles
         WHERE next_service_date IS NOT NULL
           AND next_service_date <= p_as_of + 30
         ORDER BY next_service_date
    ) LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.registration_no || ' | ' || r.vehicle_type || ' | service due: ' || TO_CHAR(r.next_service_date, 'YYYY-MM-DD') || ' | ' || r.vehicle_status);
    END LOOP;
    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No vehicles are due for service in the next 30 days.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Maintenance report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report overall, driver, and vehicle feedback averages and rating distribution.
CREATE OR REPLACE PROCEDURE sp_report_feedback_summary
IS
    v_total NUMBER;
    v_overall NUMBER(5,2);
    v_driver NUMBER(5,2);
    v_vehicle NUMBER(5,2);
BEGIN
    SELECT COUNT(*), ROUND(AVG(overall_rating), 2), ROUND(AVG(driver_rating), 2), ROUND(AVG(vehicle_rating), 2)
      INTO v_total, v_overall, v_driver, v_vehicle
      FROM feedback
     WHERE review_status <> 'Hidden';

    DBMS_OUTPUT.PUT_LINE('Visible reviews: ' || v_total);
    DBMS_OUTPUT.PUT_LINE('Average overall rating: ' || NVL(TO_CHAR(v_overall), 'N/A'));
    DBMS_OUTPUT.PUT_LINE('Average driver rating: ' || NVL(TO_CHAR(v_driver), 'N/A'));
    DBMS_OUTPUT.PUT_LINE('Average vehicle rating: ' || NVL(TO_CHAR(v_vehicle), 'N/A'));

    FOR r IN (
        SELECT overall_rating, COUNT(*) AS rating_count
          FROM feedback
         WHERE review_status <> 'Hidden'
         GROUP BY overall_rating
         ORDER BY overall_rating DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(r.overall_rating || ' stars: ' || r.rating_count);
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Feedback report failed: ' || SQLERRM);
        RAISE;
END;
/

-- Report seat occupancy and availability for trips in a date range.
CREATE OR REPLACE PROCEDURE sp_report_trip_occupancy (p_from IN DATE, p_to IN DATE)
IS
    v_found BOOLEAN := FALSE;
BEGIN
    FOR r IN (
        SELECT t.trip_id, ro.route_name, t.departure_at, t.seat_capacity,
               COUNT(CASE WHEN tk.ticket_status IN ('Reserved', 'Issued', 'Used') THEN 1 END) AS seats_taken
          FROM trips t
          JOIN routes ro ON ro.route_id = t.route_id
          LEFT JOIN tickets tk ON tk.trip_id = t.trip_id
         WHERE t.departure_at >= p_from
           AND t.departure_at < p_to + 1
         GROUP BY t.trip_id, ro.route_name, t.departure_at, t.seat_capacity
         ORDER BY t.departure_at
    ) LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.trip_id || ' | ' || r.route_name || ' | ' || TO_CHAR(r.departure_at, 'YYYY-MM-DD HH24:MI') || ' | taken: ' || r.seats_taken || ' | available: ' || GREATEST(r.seat_capacity - r.seats_taken, 0));
    END LOOP;
    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No trips were found for that date range.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Trip occupancy report failed: ' || SQLERRM);
        RAISE;
END;
/

