BEFORE INSERT OR UPDATE ON app_users
FOR EACH ROW
BEGIN
    :NEW.email := LOWER(TRIM(:NEW.email));
    IF INSERTING THEN
        :NEW.created_at := COALESCE(:NEW.created_at, SYSTIMESTAMP);
    END IF;
    :NEW.updated_at := SYSTIMESTAMP;
END;
