    feedback_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    passenger_id NUMBER NOT NULL,
    trip_id NUMBER NOT NULL,
    overall_rating NUMBER(1) NOT NULL,
    driver_rating NUMBER(1),
    vehicle_rating NUMBER(1),
    comment_text VARCHAR2(2000),
    review_status VARCHAR2(20) DEFAULT 'New' NOT NULL,
    submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_feedback PRIMARY KEY (feedback_id),
    CONSTRAINT uq_feedback_passenger_trip UNIQUE (passenger_id, trip_id),
    CONSTRAINT fk_feedback_passenger FOREIGN KEY (passenger_id) REFERENCES passengers (passenger_id),
    CONSTRAINT fk_feedback_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id),
    CONSTRAINT ck_feedback_overall CHECK (overall_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_driver CHECK (driver_rating IS NULL OR driver_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_vehicle CHECK (vehicle_rating IS NULL OR vehicle_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_feedback_status CHECK (review_status IN ('New', 'Reviewed', 'Hidden'))
);

CREATE OR REPLACE TRIGGER trg_feedback_completed_trip
BEFORE INSERT OR UPDATE OF passenger_id, trip_id ON feedback
FOR EACH ROW
DECLARE
    v_trip_status trips.trip_status%TYPE;
    v_booking_count NUMBER;
BEGIN
    SELECT trip_status
      INTO v_trip_status
      FROM trips
     WHERE trip_id = :NEW.trip_id;

    IF v_trip_status <> 'Completed' THEN
        RAISE_APPLICATION_ERROR(-20020, 'Feedback can only be submitted for completed trips.');
    END IF;

    SELECT COUNT(*)
      INTO v_booking_count
      FROM bookings
     WHERE passenger_id = :NEW.passenger_id
       AND trip_id = :NEW.trip_id
       AND booking_status = 'Completed';

    IF v_booking_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'The passenger must have completed a booking for this trip.');
    END IF;
END;
/

